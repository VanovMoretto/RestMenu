    select 1 from public.orders o
    where o.id = order_id and o.user_id = (select auth.uid())
  ));


-- -----------------------------------------------------------------------------
-- 6. RPC: create_safe_order
-- -----------------------------------------------------------------------------
-- O front manda só ids, quantidades e observações:
--   p_items = [{"menu_item_id": 12, "quantity": 2, "notes": "sem cebola"}, ...]
-- Preço, nome e total vêm SEMPRE do banco.
create or replace function public.create_safe_order(
  p_room_number    text,
  p_guest_name     text,
  p_payment_method text,
  p_items          jsonb,
  p_guest_cpf      text default null,
  p_guest_phone    text default null,
  p_notes          text default null
)
returns jsonb
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_room           text := nullif(trim(p_room_number), '');
  v_name           text := nullif(trim(p_guest_name), '');
  v_cpf            text := nullif(regexp_replace(coalesce(p_guest_cpf, ''), '\D', '', 'g'), '');
  v_phone          text := nullif(regexp_replace(coalesce(p_guest_phone, ''), '\D', '', 'g'), '');
  v_notes          text := nullif(trim(p_notes), '');
  v_payment_status text;
  v_order_id       uuid := gen_random_uuid();
  v_order_number   bigint;
  v_total          numeric(10, 2);
  v_line_count     int;
  v_inserted       int;
begin
  -- Dados do hóspede ---------------------------------------------------------
  if v_room is null or v_room !~ '^[0-9A-Za-z-]{1,10}$' then
    raise exception 'Número do quarto inválido.' using errcode = '22023';
  end if;
  if v_name is null or char_length(v_name) > 120 then
    raise exception 'Nome do hóspede inválido.' using errcode = '22023';
  end if;
  if v_cpf is not null and v_cpf !~ '^[0-9]{11}$' then
    raise exception 'CPF inválido.' using errcode = '22023';
  end if;
  if v_phone is not null and v_phone !~ '^[0-9]{8,15}$' then
    raise exception 'Telefone inválido.' using errcode = '22023';
  end if;
  if char_length(v_notes) > 500 then
    raise exception 'Observação muito longa (máx. 500 caracteres).' using errcode = '22023';
  end if;

  -- Forma de pagamento -> status inicial ---------------------------------------
  v_payment_status := case p_payment_method
    when 'pix'              then 'pending'
    when 'credit_card'      then 'pending'
    when 'room_charge'      then 'awaiting_approval'
    when 'cash_on_delivery' then 'awaiting_approval'
  end;
  if v_payment_status is null then
    raise exception 'Forma de pagamento inválida.' using errcode = '22023';
  end if;

  -- Formato dos itens ----------------------------------------------------------
  if p_items is null or jsonb_typeof(p_items) <> 'array' then
    raise exception 'Lista de itens inválida.' using errcode = '22023';
  end if;
  v_line_count := jsonb_array_length(p_items);
  if v_line_count = 0 then
    raise exception 'O pedido está vazio.' using errcode = '22023';
  end if;
  if v_line_count > 30 then
    raise exception 'Pedido com itens demais (máx. 30 linhas).' using errcode = '22023';
  end if;

  if exists (
    select 1
    from jsonb_array_elements(p_items) as e(item)
    where jsonb_typeof(e.item) <> 'object'
       or jsonb_typeof(e.item -> 'menu_item_id') is distinct from 'number'
       or jsonb_typeof(e.item -> 'quantity') is distinct from 'number'
       or (e.item -> 'notes' is not null and jsonb_typeof(e.item -> 'notes') not in ('string', 'null'))
  ) then
    raise exception 'Item do pedido em formato inválido.' using errcode = '22023';
  end if;

  if exists (
    select 1
    from jsonb_array_elements(p_items) as e(item)
    where (e.item ->> 'quantity')::numeric not between 1 and 20
       or (e.item ->> 'quantity')::numeric <> trunc((e.item ->> 'quantity')::numeric)
  ) then
    raise exception 'Quantidade deve ser um número inteiro entre 1 e 20.' using errcode = '22023';
  end if;

  if exists (
    select 1
    from jsonb_array_elements(p_items) as e(item)
    where char_length(e.item ->> 'notes') > 200
  ) then
    raise exception 'Observação do item muito longa (máx. 200 caracteres).' using errcode = '22023';
  end if;

  -- Itens existem, estão disponíveis e visíveis? -------------------------------
  if exists (
    select 1
    from jsonb_array_elements(p_items) as e(item)
    left join public.menu_items mi
      on mi.id = (e.item ->> 'menu_item_id')::bigint
     and mi.is_available
     and public.is_category_visible(mi.category_id)
    where mi.id is null
  ) then
    raise exception 'Um ou mais itens não estão disponíveis no momento.' using errcode = 'P0001';
  end if;

  if p_payment_method = 'room_charge' and exists (
    select 1
    from jsonb_array_elements(p_items) as e(item)
    join public.menu_items mi on mi.id = (e.item ->> 'menu_item_id')::bigint
    where not mi.allow_room_charge
  ) then
    raise exception 'Um ou mais itens não aceitam cobrança no quarto.' using errcode = 'P0001';
  end if;

  -- Grava pedido + itens em UM comando: preço e total saem da mesma leitura ----
  with lines as (
    select
      e.line_no,
      mi.id                               as menu_item_id,
      mi.name                             as item_name,
      (e.item ->> 'quantity')::int        as quantity,
      mi.price                            as unit_price,
      nullif(trim(e.item ->> 'notes'), '') as notes
    from jsonb_array_elements(p_items) with ordinality as e(item, line_no)
    join public.menu_items mi
      on mi.id = (e.item ->> 'menu_item_id')::bigint
     and mi.is_available
     and public.is_category_visible(mi.category_id)
     and (p_payment_method <> 'room_charge' or mi.allow_room_charge)
  ),
  new_order as (
    insert into public.orders (
      id, user_id, room_number, guest_name, guest_cpf, guest_phone,
      payment_method, payment_status, total_amount, notes
    )
    select
      v_order_id, (select auth.uid()), v_room, v_name, v_cpf, v_phone,
      p_payment_method, v_payment_status, sum(l.quantity * l.unit_price), v_notes
    from lines l
    returning id
  )
  insert into public.order_items (order_id, menu_item_id, item_name, quantity, unit_price, notes)
  select v_order_id, l.menu_item_id, l.item_name, l.quantity, l.unit_price, l.notes
  from lines l
  order by l.line_no;

  -- Rede de segurança: se algum item mudou entre a validação e a gravação,
  -- desfaz tudo (o raise faz rollback da transação inteira).
  get diagnostics v_inserted = row_count;
  if v_inserted <> v_line_count then
    raise exception 'O cardápio mudou durante o pedido. Revise o carrinho e tente de novo.' using errcode = 'P0001';
  end if;

  select o.order_number, o.total_amount
    into v_order_number, v_total
  from public.orders o
  where o.id = v_order_id;

  return jsonb_build_object(
    'order_id',       v_order_id,
    'order_number',   v_order_number,
    'total_amount',   v_total,
    'payment_status', v_payment_status
  );
end;
$$;

revoke all on function public.create_safe_order(text, text, text, jsonb, text, text, text) from public;
grant execute on function public.create_safe_order(text, text, text, jsonb, text, text, text) to anon, authenticated;


-- -----------------------------------------------------------------------------
-- 7. RPC: get_order_status (tela "acompanhe seu pedido" sem login)
-- -----------------------------------------------------------------------------
-- O order_id (UUID aleatório) funciona como "senha" do pedido: só quem criou
-- sabe. Não expõe nome, CPF nem telefone.
create or replace function public.get_order_status(p_order_id uuid)
returns table (
  order_number   bigint,
  payment_status text,
  print_status   text,
  total_amount   numeric,
  created_at     timestamptz
)
language sql
stable
security definer
set search_path = ''
as $$
  select o.order_number, o.payment_status, o.print_status, o.total_amount, o.created_at
  from public.orders o
  where o.id = p_order_id;
$$;

revoke all on function public.get_order_status(uuid) from public;
grant execute on function public.get_order_status(uuid) to anon, authenticated;


