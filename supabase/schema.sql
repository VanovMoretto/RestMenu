-- -----------------------------------------------------------------------------
-- 0. Administradores do restaurante
-- -----------------------------------------------------------------------------
-- "Autenticado" não é o mesmo que "admin": se um dia o hóspede fizer login,
-- ele também vira "authenticated". Por isso o acesso de escrita é liberado só
-- para quem está nesta tabela.
create table if not exists public.admin_users (
  user_id    uuid primary key references auth.users (id) on delete cascade,
  created_at timestamptz not null default now()
);

alter table public.admin_users enable row level security;
-- Sem policies de propósito: só o SQL Editor / service_role mexem aqui.
revoke all on public.admin_users from anon, authenticated;

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.admin_users where user_id = (select auth.uid())
  );
$$;

revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to anon, authenticated;


-- -----------------------------------------------------------------------------
-- 1. Categorias (em árvore)
-- -----------------------------------------------------------------------------
-- O cardápio atual tem 3 níveis: aba (Vinhos) > seção (Vinhos Tintos) >
-- subseção (Malbec). Em vez de 3 tabelas, cada categoria pode ter um pai:
--   parent_id null  -> aba do menu
--   parent_id = aba -> seção
--   parent_id = seção -> subseção
-- `name` é o nome em PT (usado pela cozinha). As outras línguas ficam em
-- `translations`, ex.: {"en": {"name": "Starters"}, "es": {"name": "Entradas"}}
create table if not exists public.categories (
  id           bigint generated by default as identity primary key,
  parent_id    bigint references public.categories (id) on delete restrict,
  slug         text not null unique,
  name         text not null check (char_length(trim(name)) > 0),
  translations jsonb not null default '{}'::jsonb check (jsonb_typeof(translations) = 'object'),
  sort_order   int not null default 0,
  is_active    boolean not null default true,
  created_at   timestamptz not null default now(),
  constraint categories_not_own_parent check (parent_id is null or parent_id <> id)
);

create index if not exists categories_parent_sort_idx on public.categories (parent_id, sort_order);

-- Uma categoria só aparece se ela e todos os "pais" estiverem ativos.
-- security definer: lê a tabela sem passar pelo RLS (evita recursão na policy).
create or replace function public.is_category_visible(p_category_id bigint)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  with recursive chain as (
    select c.id, c.parent_id, c.is_active, 1 as depth
    from public.categories c
    where c.id = p_category_id
    union all
    select c.id, c.parent_id, c.is_active, chain.depth + 1
    from public.categories c
    join chain on c.id = chain.parent_id
    where chain.depth < 10 -- trava contra ciclos acidentais
  )
  select coalesce(bool_and(is_active), false) from chain;
$$;

revoke all on function public.is_category_visible(bigint) from public;
grant execute on function public.is_category_visible(bigint) to anon, authenticated;


-- -----------------------------------------------------------------------------
-- 2. Itens do cardápio
-- -----------------------------------------------------------------------------
-- `translations`: {"en": {"name": "...", "description": "..."}, "es": {...}}
-- `serving_type` e `show_picture_icon` substituem `servingType` e `picture`
-- do menuData.ts. `slug` guarda o id antigo do front (c1, cn2, v14...).
create table if not exists public.menu_items (
  id                bigint generated by default as identity primary key,
  category_id       bigint not null references public.categories (id) on delete restrict,
  slug              text unique,
  name              text not null check (char_length(trim(name)) > 0),
  description       text,
  translations      jsonb not null default '{}'::jsonb check (jsonb_typeof(translations) = 'object'),
  price             numeric(10, 2) not null check (price >= 0),
  image_url         text,
  serving_type      text check (serving_type in ('bottle', 'glass')),
  show_picture_icon boolean not null default false,
  is_available      boolean not null default true,  -- pausar prato em falta
  allow_room_charge boolean not null default false, -- aceita "pendurar no quarto"?
  sort_order        int not null default 0,
  created_at        timestamptz not null default now()
);

create index if not exists menu_items_category_sort_idx on public.menu_items (category_id, sort_order);


-- -----------------------------------------------------------------------------
-- 3. Pedidos
-- -----------------------------------------------------------------------------
-- payment_status:
--   pending           -> pix/cartão criado, aguardando o gateway
--   awaiting_approval -> room_charge/dinheiro, aguardando a equipe aprovar
--   approved          -> room_charge/dinheiro liberado pela equipe (ainda não recebido)
--   paid              -> pago (webhook do gateway ou baixa manual)
--   cancelled
-- Fila da impressora: payment_status in ('paid', 'approved') and print_status = 'pending'
create table if not exists public.orders (
  id                  uuid primary key default gen_random_uuid(),
  order_number        bigint generated always as identity (start with 101) unique,
  user_id             uuid references auth.users (id) on delete set null,
  room_number         text not null check (room_number ~ '^[0-9A-Za-z-]{1,10}$'),
  guest_name          text not null check (char_length(guest_name) between 1 and 120),
  guest_cpf           text check (guest_cpf ~ '^[0-9]{11}$'),       -- opcional: estrangeiro não tem CPF
  guest_phone         text check (guest_phone ~ '^[0-9]{8,15}$'),   -- só dígitos, com DDI se houver
  payment_method      text not null check (payment_method in ('pix', 'credit_card', 'room_charge', 'cash_on_delivery')),
  payment_status      text not null default 'pending'
                      check (payment_status in ('pending', 'awaiting_approval', 'approved', 'paid', 'cancelled')),
  payment_provider_id text unique, -- id da cobrança no gateway (usado pelo webhook)
  print_status        text not null default 'pending' check (print_status in ('pending', 'printed', 'error')),
  total_amount        numeric(10, 2) not null check (total_amount >= 0),
  notes               text check (char_length(notes) <= 500),
  created_at          timestamptz not null default now(),
  updated_at          timestamptz not null default now()
);

create index if not exists orders_created_at_idx on public.orders (created_at desc);
create index if not exists orders_user_id_idx on public.orders (user_id);
create index if not exists orders_print_queue_idx on public.orders (created_at)
  where print_status = 'pending' and payment_status in ('paid', 'approved');

create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists orders_set_updated_at on public.orders;
create trigger orders_set_updated_at
  before update on public.orders
  for each row execute function public.set_updated_at();


-- -----------------------------------------------------------------------------
-- 4. Itens do pedido
-- -----------------------------------------------------------------------------
-- item_name e unit_price são "fotografias" do momento da compra: mudar o preço
-- ou apagar o prato depois não altera pedidos antigos.
create table if not exists public.order_items (
  id           bigint generated by default as identity primary key,
  order_id     uuid not null references public.orders (id) on delete cascade,
  menu_item_id bigint references public.menu_items (id) on delete set null,
  item_name    text not null,
  quantity     int not null check (quantity between 1 and 20),
  unit_price   numeric(10, 2) not null check (unit_price >= 0),
  line_total   numeric(10, 2) generated always as (quantity * unit_price) stored,
  notes        text check (char_length(notes) <= 200)
);

create index if not exists order_items_order_id_idx on public.order_items (order_id);
create index if not exists order_items_menu_item_id_idx on public.order_items (menu_item_id);


